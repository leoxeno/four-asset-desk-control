"""Build the scoreboard in results.md from grading.yml.

grading.yml holds verdicts and one-line notes only. The table, the tallies and
the win / tie / loss call per question are computed here, so results.md never
carries a hand-typed count.

Usage:
    python3 tools/score.py            # print the markdown block
    python3 tools/score.py --write    # replace the block between the markers in results.md
"""
import argparse
import pathlib

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results.md"
RANK = {"wrong": 0, "partial": 1, "correct": 2, "not run": None}

# Two grading files, two marker blocks in results.md. Select with --block.
BLOCKS = {
    "scoreboard": (ROOT / "grading.yml", "<!-- scoreboard:start (generated by tools/score.py, do not edit by hand) -->", "<!-- scoreboard:end -->"),
    "outside": (ROOT / "outside-check" / "grading.yml", "<!-- outside:start (generated by tools/score.py --block outside, do not edit by hand) -->", "<!-- outside:end -->"),
}


def call(control: str, treatment: str) -> str:
    c, t = RANK.get(control), RANK.get(treatment)
    if c is None or t is None:
        return "not run"
    if t > c:
        return "folder win"
    if t < c:
        return "folder loss"
    return "tie"


def build(grading: pathlib.Path) -> str:
    data = yaml.safe_load(grading.read_text())
    arms = data["arms"]
    questions = data["questions"]
    headline = f"{arms[1]} vs {arms[0]}"
    sort_key = (lambda k: int(k)) if all(str(k).isdigit() for k in questions) else (lambda k: str(k))
    lines = ["| # | " + " | ".join(arms) + f" | {headline} | note |", "|---|" + "---|" * (len(arms) + 2)]
    tallies = {arm: {"correct": 0, "partial": 0, "wrong": 0, "not run": 0} for arm in arms}
    calls = {arm: {"folder win": 0, "tie": 0, "folder loss": 0, "not run": 0} for arm in arms[1:]}
    for number in sorted(questions, key=sort_key):
        row = questions[number]
        verdicts = [row.get(arm, {}).get("verdict", "not run") for arm in arms]
        for arm, verdict in zip(arms, verdicts):
            tallies[arm][verdict] += 1
        control = row.get(arms[0], {}).get("verdict", "not run")
        for arm in arms[1:]:                      # every folder arm against the control; the column shows the first
            calls[arm][call(control, row.get(arm, {}).get("verdict", "not run"))] += 1
        c = call(control, row.get(arms[1], {}).get("verdict", "not run"))
        note = row.get("note", "")
        lines.append(f"| {number} | " + " | ".join(verdicts) + f" | {c} | {note} |")
    lines.append("")
    for arm in arms:
        t = tallies[arm]
        lines.append(f"- {arm}: {t['correct']} correct, {t['partial']} partial, {t['wrong']} wrong" + (f", {t['not run']} not run" if t["not run"] else ""))
    for arm in arms[1:]:
        k = calls[arm]
        lines.append(f"- {arm} vs {arms[0]}: {k['folder win']} wins, {k['tie']} ties, {k['folder loss']} losses" + (f", {k['not run']} not run" if k["not run"] else ""))
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--block", choices=list(BLOCKS), default="scoreboard")
    args = parser.parse_args()
    grading, start, end = BLOCKS[args.block]
    block = build(grading)
    if not args.write:
        print(block)
        return
    text = RESULTS.read_text()
    if start not in text or end not in text:
        raise SystemExit(f"markers for {args.block} not found in {RESULTS.name}")
    head, rest = text.split(start, 1)
    _, tail = rest.split(end, 1)
    RESULTS.write_text(head + start + "\n" + block + "\n" + end + tail)
    print(f"updated {args.block} block in {RESULTS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
